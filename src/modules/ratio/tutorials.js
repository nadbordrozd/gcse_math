/**
 * Bar model: one row per person/colour, each row made of equal boxes ("parts").
 * rows: [[label, numberOfParts, valueInEachBox?], ...]
 */
function barModel(rows, { box = 44, caption = '' } = {}) {
  const left = 90; const rowH = 46;
  const maxParts = Math.max(...rows.map((r) => r[1]));
  let body = '';
  rows.forEach(([label, n, val], i) => {
    const y = 14 + i * rowH;
    body += text(left - 10, y + 15, label, { anchor: 'end', size: 15 });
    for (let k = 0; k < n; k += 1) {
      body += rect(left + k * box, y, box, 30, { fill: i % 2 ? FILL2 : FILL, width: 1.5 });
      if (val !== undefined) body += text(left + k * box + box / 2, y + 15, String(val), { size: 13 });
    }
  });
  const w = left + maxParts * box + 20; const hgt = 14 + rows.length * rowH;
  return figure(svg(w, hgt, body, { maxWidth: Math.min(480, w), label: 'Bar model of a ratio' }), caption);
}

/** The distance–speed–time triangle. */
function dstTriangle() {
  const body = line(60, 170, 200, 170) + line(60, 170, 130, 30) + line(130, 30, 200, 170) + line(88, 115, 172, 115)
    + line(130, 115, 130, 170)
    + text(130, 82, 'D', { size: 22, bold: true }) + text(105, 145, 'S', { size: 22, bold: true }) + text(155, 145, 'T', { size: 22, bold: true });
  return figure(svg(260, 190, body, { maxWidth: 260, label: 'Distance, speed, time triangle' }), 'Cover the one you want: D = S × T, S = D ÷ T, T = D ÷ S.');
}

