// Number line 5 to 7 showing 5.5 <= l < 6.5 (closed at 5.5, open at 6.5).
function intervalLine() {
  const nl = numberLine({ min: 5, max: 7, step: 0.5, labelEvery: 1, width: 400 });
  return nl.svg(inequalityMark(nl, 5.5, 6.5, { closedFrom: true, closedTo: false })
    + text(nl.X(6), nl.y - 30, 'rounds to 6', { size: 13, color: ACCENT }));
}

