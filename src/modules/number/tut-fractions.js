// Two bars of the same length: 3/5 and 6/10 shaded.
function fractionBars() {
  const W = 300; const x0 = 70;
  const bar = (y, n, k, label) => {
    let s = text(x0 - 14, y + 16, label, { anchor: 'end', size: 16 });
    for (let i = 0; i < n; i += 1) s += rect(x0 + (i * W) / n, y, W / n, 32, { fill: i < k ? ACCENT : FILL, width: 1.5 });
    return s;
  };
  return svg(390, 110, bar(14, 5, 3, '3/5') + bar(62, 10, 6, '6/10'), { maxWidth: 390, label: 'Bars showing 3/5 and 6/10 are the same amount' });
}

