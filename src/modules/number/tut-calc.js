// Number line from -8 to 8 with two jumps drawn above it: start -3, go down 5 to -8.
function negativeLine() {
  const nl = numberLine({ min: -8, max: 8, step: 1, labelEvery: 2, width: 440 });
  const y = nl.y - 14;
  return nl.svg(arrow(nl.X(-3), y, nl.X(-8) + 3, y, { color: ACCENT, width: 2.2 })
    + text((nl.X(-3) + nl.X(-8)) / 2, y - 12, '− 5', { size: 13, color: ACCENT })
    + arrow(nl.X(2), y, nl.X(6) - 3, y, { color: ACCENT2, width: 2.2 })
    + text((nl.X(2) + nl.X(6)) / 2, y - 12, '+ 4', { size: 13, color: ACCENT2 }));
}

// Number line 3 to 4 split into tenths with an arrow at 3.7.
function tenthsLine() {
  const nl = numberLine({ min: 3, max: 4, step: 0.1, labelEvery: 10, width: 420 });
  const x = nl.X(3.7);
  return nl.svg(arrow(x, 4, x, nl.y - 9, { color: ACCENT, width: 2.4 }));
}

