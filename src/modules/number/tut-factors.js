// Factor tree for 360 = 36 × 10, 36 = 4 × 9, 4 = 2 × 2, 9 = 3 × 3, 10 = 2 × 5. Primes are circled.
function factorTree() {
  const nodes = [
    { x: 200, y: 25, t: '360' },
    { x: 120, y: 85, t: '36', from: 0 }, { x: 290, y: 85, t: '10', from: 0 },
    { x: 70, y: 145, t: '4', from: 1 }, { x: 165, y: 145, t: '9', from: 1 },
    { x: 260, y: 145, t: '2', from: 2, prime: true }, { x: 325, y: 145, t: '5', from: 2, prime: true },
    { x: 40, y: 205, t: '2', from: 3, prime: true }, { x: 100, y: 205, t: '2', from: 3, prime: true },
    { x: 140, y: 205, t: '3', from: 4, prime: true }, { x: 195, y: 205, t: '3', from: 4, prime: true },
  ];
  let body = '';
  nodes.forEach((n) => { if (n.from !== undefined) { const f = nodes[n.from]; body += line(f.x, f.y + 12, n.x, n.y - 12, { width: 1.6 }); } });
  nodes.forEach((n) => {
    if (n.prime) body += circle(n.x, n.y, 15, { color: ACCENT, width: 2 });
    body += text(n.x, n.y, n.t, { size: 16, bold: !n.prime, color: n.prime ? ACCENT : 'currentColor' });
  });
  return svg(370, 230, body, { maxWidth: 370, label: 'Factor tree for 360' });
}

// Venn diagram of the prime factors of 36 and 60.
function primeVenn() {
  let body = circle(150, 115, 85, { color: ACCENT, width: 2 }) + circle(250, 115, 85, { color: ACCENT2, width: 2 });
  body += text(110, 20, '36', { bold: true, color: ACCENT }) + text(290, 20, '60', { bold: true, color: ACCENT2 });
  body += text(105, 115, '3', { size: 18 });
  body += text(200, 92, '2', { size: 18 }) + text(200, 117, '2', { size: 18 }) + text(200, 142, '3', { size: 18 });
  body += text(295, 115, '5', { size: 18 });
  return svg(400, 215, body, { maxWidth: 400, label: 'Venn diagram of prime factors of 36 and 60' });
}

