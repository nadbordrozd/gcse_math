// Grid ("area") picture for (x + a)(x + b).
function areaGrid(a, b) {
  const X = 60; const Y = 40; const W1 = 150; const W2 = 60; const H1 = 110; const H2 = 50;
  const cell = (x, y, w, hh, label, fill) => rect(x, y, w, hh, { fill }) + text(x + w / 2, y + hh / 2, label, { italic: true });
  return svg(320, 230,
    cell(X, Y, W1, H1, 'x²', 'var(--d-fill, #e8eefc)') + cell(X + W1, Y, W2, H1, `${b}x`, 'var(--d-fill2, #fde9d9)')
    + cell(X, Y + H1, W1, H2, `${a}x`, 'var(--d-fill2, #fde9d9)') + cell(X + W1, Y + H1, W2, H2, `${a * b}`, 'var(--d-fill, #e8eefc)')
    + text(X + W1 / 2, Y - 14, 'x', { italic: true }) + text(X + W1 + W2 / 2, Y - 14, `+ ${b}`)
    + text(X - 16, Y + H1 / 2, 'x', { italic: true }) + text(X - 20, Y + H1 + H2 / 2, `+ ${a}`),
  { maxWidth: 320, label: `Area model for (x + ${a})(x + ${b})` });
}

// Triangle with algebraic side labels, for the perimeter example.
function labelledTriangle() {
  const A = [50, 180]; const B = [310, 180]; const C = [200, 40];
  return svg(360, 210, polygon([A, B, C]) + text(180, 200, '3a + 2', { italic: true }) + text(285, 100, 'a + 5', { italic: true }) + text(95, 100, '2a − 1', { italic: true }),
    { maxWidth: 360, label: 'Triangle with sides 3a + 2, a + 5 and 2a − 1' });
}

