// Number line with an inequality marked.
function ineqLine(from, to, opts, min = -5, max = 6) {
  const nl = numberLine({ min, max, width: 440 });
  return nl.svg(inequalityMark(nl, from, to, opts));
}

// Sketch of y = (x − 4)(x + 3), showing where it is below the x-axis.
function parabolaSketch() {
  // A sketch: y is drawn at 1/3 scale (no y labels) so the curve fits a normal-sized picture.
  const pl = plane({ xmin: -5, xmax: 6, ymin: -5, ymax: 4, unitPx: 30, grid: false, labels: false });
  const f = (x) => ((x - 4) * (x + 3)) / 3;
  const shade = pl.plot(f, { from: -3, to: 4, color: 'var(--d-accent2, #c2410c)', width: 4 });
  return pl.wrap(pl.plot(f) + shade + pl.point(-3, 0, '−3', { dx: -16, dy: -12 }) + pl.point(4, 0, '4', { dx: 12, dy: -12 }));
}

// Two straight lines crossing, for simultaneous equations.
function linesSketch() {
  const pl = plane({ xmin: 0, xmax: 10, ymin: -4, ymax: 18, unitPx: 18, ystep: 2, ylabelEvery: 2, grid: true });
  const labels = text(pl.X(3.4), pl.Y(14), '2x + y = 18', { italic: true, anchor: 'start', color: 'var(--d-accent, #2f5bd3)', size: 14 })
    + text(pl.X(4.6), pl.Y(-3), 'x − y = 6', { italic: true, anchor: 'start', color: 'var(--d-accent2, #c2410c)', size: 14 });
  return pl.wrap(pl.plot((x) => 18 - 2 * x) + pl.plot((x) => x - 6, { color: 'var(--d-accent2, #c2410c)' }) + pl.point(8, 2, '(8, 2)', { dx: 22, dy: -12 }) + labels);
}

// Balance picture for 3x + 5 = 20.
function balance() {
  return svg(360, 130, rect(20, 30, 150, 60, { fill: 'var(--d-fill, #e8eefc)' }) + text(95, 60, '3x + 5', { italic: true, size: 18 })
    + text(180, 60, '=', { size: 22 }) + rect(190, 30, 150, 60, { fill: 'var(--d-fill2, #fde9d9)' }) + text(265, 60, '20', { size: 18 })
    + text(180, 112, 'Do the same to both sides to keep it balanced', { size: 13 }), { maxWidth: 360, label: 'Both sides of an equation balance' });
}

